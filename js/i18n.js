/**
 * 判斷一個 BCP 47 語系字串是否屬於「繁體中文」。
 * 僅以下情況視為繁中：
 *   - 腳本標籤為 Hant，例如 zh-Hant、zh-Hant-TW、zh-Hant-HK
 *   - 地區為傳統繁中使用地：TW (台灣)、HK (香港)、MO (澳門)
 * 其他中文變體 (zh-CN / zh-SG / zh-Hans …) 一律視為非繁中 → 使用英文。
 */
function isTraditionalChinese(tag) {
    if (!tag) return false;
    const parts = String(tag).toLowerCase().split(/[-_]/);
    if (parts[0] !== 'zh') return false;
    for (let i = 1; i < parts.length; i++) {
        const p = parts[i];
        if (p === 'hant') return true;
        if (p === 'hans') return false;
        if (p === 'tw' || p === 'hk' || p === 'mo') return true;
        if (p === 'cn' || p === 'sg' || p === 'my') return false;
    }
    return false;
}

let currentLang = (() => {
    try {
        const saved = localStorage.getItem('pcviewer.lang');
        if (saved && I18N[saved]) return saved;
    } catch (_) {}
    // 依瀏覽器語系自動判斷：僅繁體中文 → zh-Hant，其餘 (含簡體中文) → en
    const candidates = [];
    if (Array.isArray(navigator.languages)) candidates.push(...navigator.languages);
    if (navigator.language) candidates.push(navigator.language);
    for (const tag of candidates) {
        if (isTraditionalChinese(tag)) return 'zh-Hant';
    }
    return 'en';
})();

